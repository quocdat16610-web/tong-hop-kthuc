/// Nét viết tay giả lập: nghiêng, co giãn ngang, rung tay, đảo chiều nét ngẫu nhiên. `at` = góc trên-trái.
List<List<num>> ink(List<S> strokes, math.Random r, {double size = 50, (double, double)? at}) {
  final slant = (r.nextDouble() - .5) * .5, ax = .75 + r.nextDouble() * .5;
  final ox = at?.$1 ?? r.nextDouble() * 500, oy = at?.$2 ?? r.nextDouble() * 500;
  return [for (var s in strokes) () {
    if (r.nextBool()) s = s.reversed.toList();
    final out = <num>[];
    for (var i = 0; i + 1 < s.length; i++) {
      final (x0, y0) = s[i]; final (x1, y1) = s[i + 1];
      final n = math.max(2, (math.sqrt(math.pow(x1-x0,2)+math.pow(y1-y0,2)) * size / 3).round());
      for (var k = 0; k < n; k++) { final t = k / n; var x = x0 + (x1 - x0) * t, y = y0 + (y1 - y0) * t;
        x = (x * ax * 0.7 + slant * (1 - y)) * size; y = y * size;
        out.addAll([ox + x + (r.nextDouble() - .5) * size * .04, oy + y + (r.nextDouble() - .5) * size * .04]); }
    }
    final (x, y) = s.last; out.addAll([ox + (x * ax * .7 + slant * (1 - y)) * size, oy + y * size]);
    return out; }()];
}
